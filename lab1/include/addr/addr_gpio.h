#ifndef ADDR_GPIO_H
#define ADDR_GPIO_H

#include "addr_base.h"

/* GPIO register offsets from GPIO_BASE. */
#define GPFSEL0_OFFSET   0x00UL
#define GPFSEL1_OFFSET   0x04UL
#define GPFSEL2_OFFSET   0x08UL
#define GPFSEL3_OFFSET   0x0CUL
#define GPFSEL4_OFFSET   0x10UL
#define GPFSEL5_OFFSET   0x14UL
#define GPSET0_OFFSET    0x1CUL
#define GPSET1_OFFSET    0x20UL
#define GPCLR0_OFFSET    0x28UL
#define GPCLR1_OFFSET    0x2CUL
#define GPLEV0_OFFSET    0x34UL
#define GPLEV1_OFFSET    0x38UL
#define GPPUD_OFFSET     0x94UL
#define GPPUDCLK0_OFFSET 0x98UL
#define GPPUDCLK1_OFFSET 0x9CUL

#define GPFSEL0   MMIO_REG32(GPIO_BASE + GPFSEL0_OFFSET)
#define GPFSEL1   MMIO_REG32(GPIO_BASE + GPFSEL1_OFFSET)
#define GPFSEL2   MMIO_REG32(GPIO_BASE + GPFSEL2_OFFSET)
#define GPFSEL3   MMIO_REG32(GPIO_BASE + GPFSEL3_OFFSET)
#define GPFSEL4   MMIO_REG32(GPIO_BASE + GPFSEL4_OFFSET)
#define GPFSEL5   MMIO_REG32(GPIO_BASE + GPFSEL5_OFFSET)
#define GPSET0    MMIO_REG32(GPIO_BASE + GPSET0_OFFSET)
#define GPSET1    MMIO_REG32(GPIO_BASE + GPSET1_OFFSET)
#define GPCLR0    MMIO_REG32(GPIO_BASE + GPCLR0_OFFSET)
#define GPCLR1    MMIO_REG32(GPIO_BASE + GPCLR1_OFFSET)
#define GPLEV0    MMIO_REG32(GPIO_BASE + GPLEV0_OFFSET)
#define GPLEV1    MMIO_REG32(GPIO_BASE + GPLEV1_OFFSET)
#define GPPUD     MMIO_REG32(GPIO_BASE + GPPUD_OFFSET)
#define GPPUDCLK0 MMIO_REG32(GPIO_BASE + GPPUDCLK0_OFFSET)
#define GPPUDCLK1 MMIO_REG32(GPIO_BASE + GPPUDCLK1_OFFSET)

#endif /* ADDR_GPIO_H */
