#ifndef ADDR_UART_H
#define ADDR_UART_H

#include "addr_base.h"

/* Auxiliary and mini UART register offsets from AUX_BASE. */
#define AUX_IRQ_OFFSET        0x00UL
#define AUX_ENABLES_OFFSET    0x04UL
#define AUX_MU_IO_OFFSET      0x40UL
#define AUX_MU_IER_OFFSET     0x44UL
#define AUX_MU_IIR_OFFSET     0x48UL
#define AUX_MU_LCR_OFFSET     0x4CUL
#define AUX_MU_MCR_OFFSET     0x50UL
#define AUX_MU_LSR_OFFSET     0x54UL
#define AUX_MU_MSR_OFFSET     0x58UL
#define AUX_MU_SCRATCH_OFFSET 0x5CUL
#define AUX_MU_CNTL_OFFSET    0x60UL
#define AUX_MU_STAT_OFFSET    0x64UL
#define AUX_MU_BAUD_OFFSET    0x68UL

#define AUX_IRQ        MMIO_REG32(AUX_BASE + AUX_IRQ_OFFSET)
#define AUX_ENABLES    MMIO_REG32(AUX_BASE + AUX_ENABLES_OFFSET)
#define AUX_MU_IO_REG      MMIO_REG32(AUX_BASE + AUX_MU_IO_OFFSET)
#define AUX_MU_IER_REG     MMIO_REG32(AUX_BASE + AUX_MU_IER_OFFSET)
#define AUX_MU_IIR_REG     MMIO_REG32(AUX_BASE + AUX_MU_IIR_OFFSET)
#define AUX_MU_LCR_REG     MMIO_REG32(AUX_BASE + AUX_MU_LCR_OFFSET)
#define AUX_MU_MCR_REG     MMIO_REG32(AUX_BASE + AUX_MU_MCR_OFFSET)
#define AUX_MU_LSR_REG     MMIO_REG32(AUX_BASE + AUX_MU_LSR_OFFSET)
#define AUX_MU_MSR_REG     MMIO_REG32(AUX_BASE + AUX_MU_MSR_OFFSET)
#define AUX_MU_SCRATCH MMIO_REG32(AUX_BASE + AUX_MU_SCRATCH_OFFSET)
#define AUX_MU_CNTL_REG    MMIO_REG32(AUX_BASE + AUX_MU_CNTL_OFFSET)
#define AUX_MU_STAT_REG    MMIO_REG32(AUX_BASE + AUX_MU_STAT_OFFSET)
#define AUX_MU_BAUD    MMIO_REG32(AUX_BASE + AUX_MU_BAUD_OFFSET)

void uart_init(void);

#endif /* ADDR_UART_H */
